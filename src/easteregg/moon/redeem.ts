// =============================================================================
// ⛔ 临时彩蛋:中秋兑换码(状态 + 文案)
// -----------------------------------------------------------------------------
// 这份文件存在的唯一目的:把"兑换码"这颗彩蛋的状态与文案收在一处,
// 让 SettingsDialog(关于页的输入框)与 MoonEgg(月亮浮层)都只依赖它,
// 将来删彩蛋时连同本目录一起删掉即可(见同目录 README.md)。
//
// 三条硬约定:
//   1. 状态**只在内存**(一个模块级 ref):不写 localStorage、不进 pinia,
//      刷新页面就等于没兑换过 —— 月亮消失,要重新输码。
//   2. 兑换成功之前,月亮那一坨(three / cannon-es / glb / draco)**一个字节都不下载**:
//      MoonEgg 里的 MoonViewer 是异步组件,且只在 `moonRedeemed` 为真时才被渲染,
//      所以动态 import 的时机 = 兑换成功的瞬间(见 MoonEgg.vue)。
//   3. 提示文案也只在这里写一份:兑换成功后显示在关于页输入框下方的那行绿色小字。
// =============================================================================
import { ref } from 'vue'

/** 兑换码(中秋彩蛋) */
export const MOON_REDEEM_CODE = '中秋快乐'

/**
 * 月亮操作提示
 *
 * 以前是浮在月亮上方的一行字;按要求改成**兑换成功后**显示在关于页的绿色小字,
 * 所以它现在由关于页那块 UI 渲染,月亮那一层不再画任何文字。
 */
export const MOON_HINT =
  '拖动月亮甩出会弹跳 · 滚轮 / 双指缩放 · 右键 / 长按菜单 · 手机倾斜月亮会跟着滚（无需设置）'

/**
 * 是否已兑换成功
 *
 * 刻意就是一个普通 ref:没有持久化、没有初始值来源,刷新即 false。
 */
export const moonRedeemed = ref(false)

/**
 * 校验兑换码
 *
 * @returns 是否兑换成功;成功后置位(幂等,重复兑换也返回 true)
 */
export function redeemMoon(code: string): boolean {
  if (code.trim() !== MOON_REDEEM_CODE) return false
  moonRedeemed.value = true
  return true
}
